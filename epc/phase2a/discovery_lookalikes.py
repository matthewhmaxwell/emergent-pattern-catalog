def p34_ba_growth(seed: int, N: int = 200, m: int = 2, n_frames: int = 80) -> List[Dict[str, Any]]:
    """Barabasi-Albert growth on a fixed node set: nodes not yet born are isolated."""
    rng = np.random.default_rng(seed)
    A = np.zeros((N, N), dtype=np.int8)
    m0 = m + 1
    for i in range(m0):
        for j in range(i + 1, m0):
            A[i, j] = A[j, i] = 1
    deg = A.sum(1).astype(float)
    frames: List[Dict[str, Any]] = []
    births = list(range(m0, N))
    snap = max(1, len(births) // n_frames)
    for k, new in enumerate(births):
        p = deg[:new] / deg[:new].sum()
        targets = rng.choice(new, size=m, replace=False, p=p)
        for t in targets:
            A[new, t] = A[t, new] = 1
            deg[t] += 1
        deg[new] = m
        if k % snap == 0:
            frames.append({"adjacency": A.copy(), "step": k})
    frames.append({"adjacency": A.copy(), "step": len(births)})
    return frames


