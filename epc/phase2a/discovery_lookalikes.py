def p37_may_leonard(seed: int, alpha: float = 0.8, beta: float = 1.2, t_max: float = 1000.0,
                    dt: float = 0.05, n_frames: int = 80) -> List[Dict[str, Any]]:
    """dx_i/dt = x_i (1 - x_i - alpha x_{i+1} - beta x_{i+2}), RK4; alpha+beta = 2
    gives neutrally stable closed orbits (sustained LV-type oscillation)."""
    rng = np.random.default_rng(seed)
    x = np.array([0.45, 0.30, 0.15]) + 0.02 * rng.random(3)
    M = np.array([[1.0, alpha, beta], [beta, 1.0, alpha], [alpha, beta, 1.0]])

    def f(v):
        return v * (1.0 - M @ v)

    n_steps = int(t_max / dt)
    snap = max(1, n_steps // n_frames)
    frames = [{"abundances": x.copy(), "resources": np.array([1.0 - x.sum()]), "step": 0}]
    for s in range(1, n_steps + 1):
        k1 = f(x); k2 = f(x + 0.5 * dt * k1); k3 = f(x + 0.5 * dt * k2); k4 = f(x + dt * k3)
        x = np.clip(x + dt / 6.0 * (k1 + 2 * k2 + 2 * k3 + k4), 0.0, None)
        if s % snap == 0:
            frames.append({"abundances": x.copy(), "resources": np.array([max(1.0 - x.sum(), 0.0)]),
                           "step": s})
    return frames


def p37_forced_stable_coexistence(seed: int, amp: float = 0.3, period: float = 100.0,
                                  t_max: float = 3000.0, dt: float = 0.02,
                                  n_frames: int = 80) -> List[Dict[str, Any]]:
    """The standalone stable-coexistence chemostat (same K, C, S, r, m, D and
    jitter construction as epc.models.resource_competition.neg_stable_coexistence)
    with seasonally forced supply."""
    rng = np.random.default_rng(seed * 13 + 5)
    n = 5
    K = np.full((n, n), 0.02); C = np.full((n, n), 0.001)
    for i in range(n):
        K[i, i] = 0.5; C[i, i] = 0.10
    K *= 1 + 0.03 * rng.standard_normal((n, n)); C *= 1 + 0.03 * rng.standard_normal((n, n))
    K = np.clip(K, 0.005, None); C = np.clip(C, 0.0005, None)
    S0 = np.full(n, 10.0); r = np.full(n, 1.0); m = np.full(n, 0.25); D = 0.25
    N = 0.1 + 0.02 * rng.random(n); R = S0.copy()
    n_steps = int(t_max / dt)
    snap = max(1, n_steps // n_frames)
    frames = [{"abundances": N.copy(), "resources": R.copy(), "step": 0}]
    for s in range(1, n_steps + 1):
        S = S0 * (1.0 + amp * np.sin(2.0 * np.pi * (s * dt) / period))
        ratio = R[:, None] / (K + R[:, None])
        mu = r * ratio.min(axis=0)
        dN = N * (mu - m)
        consumption = (C * (mu * N)[None, :]).sum(axis=1)
        dR = D * (S - R) - consumption
        N = np.clip(N + dt * dN, 0.0, None)
        R = np.clip(R + dt * dR, 0.0, None)
        if s % snap == 0:
            frames.append({"abundances": N.copy(), "resources": R.copy(), "step": s})
    return frames


